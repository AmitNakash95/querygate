"""`querygate-performance-benchmark` — measure QueryGate's per-request overhead.

Runs a small, self-contained set of query scenarios against a real Postgres
instance (default: the local demo database from ``make compose-up``) and
reports, per scenario, three latency tiers: raw SQL baseline, the in-process
request pipeline, and a full REST round trip. See
``querygate.performance_benchmark`` for methodology and
``docs/business/PERFORMANCE_BENCHMARK.md`` for the published write-up.

This is informational, not pass/fail — exit code is always 0 on a completed
run (non-zero only on an error, e.g. no reachable database). Pass
``--max-overhead-ms`` for an optional local sanity check.
"""

from __future__ import annotations

import argparse
import logging
import os
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

# querygate.core.logging binds a module-level default logger at import time,
# reading LOG_LEVEL then — so this must be set before the first `import
# querygate...` below, or the app's own request/audit logging (which this
# benchmark's REST tier triggers for real) drowns out the report on stdout.
os.environ.setdefault("LOG_LEVEL", "WARNING")
logging.getLogger("httpx").setLevel(logging.WARNING)

import asyncio  # noqa: E402

from querygate.performance_benchmark import (  # noqa: E402
    DEFAULT_CONNECTION_STRING,
    PerformanceBenchmarkReport,
    run_performance_benchmark,
)

_REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MARKDOWN_PATH = _REPO_ROOT / "docs" / "business" / "PERFORMANCE_BENCHMARK_RESULTS.md"


def _row(*cols: str) -> str:
    widths = (16, 12, 12, 12, 12, 12)
    return "".join(col.ljust(w) for col, w in zip(cols, widths))


def _print_report(report: PerformanceBenchmarkReport) -> None:
    print("QueryGate performance benchmark")
    print(
        f"  seeded rows: {report.seeded_rows}, iterations/scenario: "
        f"{report.iterations_per_scenario} (+{report.warmup_per_scenario} warmup)"
    )
    print("=" * 88)
    print(_row("scenario", "tier", "mean ms", "p50 ms", "p95 ms", "p99 ms"))
    print("-" * 88)
    for scenario in report.scenarios:
        for tier_name, stats in (
            ("baseline", scenario.baseline),
            ("pipeline", scenario.pipeline),
            ("rest", scenario.rest),
        ):
            print(
                _row(
                    scenario.name,
                    tier_name,
                    f"{stats.mean_ms:.2f}",
                    f"{stats.p50_ms:.2f}",
                    f"{stats.p95_ms:.2f}",
                    f"{stats.p99_ms:.2f}",
                )
            )
        print(
            f"{'':<16}overhead: pipeline +{scenario.pipeline_overhead_ms:.2f}ms, "
            f"rest +{scenario.rest_overhead_ms:.2f}ms "
            f"({scenario.rest_overhead_pct:.0f}% of baseline)"
        )
        print(f"  {scenario.description}")
        print("-" * 88)

    print(
        f"Mean pipeline overhead (no HTTP): {report.mean_pipeline_overhead_ms:.2f} ms/query\n"
        f"Mean REST overhead (full round trip): {report.mean_rest_overhead_ms:.2f} ms/query"
    )
    print(
        "\nAll figures are wall-clock milliseconds, in-process (ASGI transport, no real\n"
        "socket/TLS). See docs/business/PERFORMANCE_BENCHMARK.md for methodology."
    )


def _render_markdown(report: PerformanceBenchmarkReport) -> str:
    """A fresh, publish-ready results snapshot for THIS run only — data, not
    analysis. Interpretation lives in the hand-maintained
    ``PERFORMANCE_BENCHMARK.md``, which this file links to rather than
    duplicates, so a regenerated results file can never silently overwrite
    curated methodology prose."""
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# QueryGate performance benchmark — latest results",
        "",
        "**Auto-generated by `make performance-benchmark` — do not hand-edit; it",
        "is overwritten on every run.** Data only, no interpretation — see",
        "[PERFORMANCE_BENCHMARK.md](PERFORMANCE_BENCHMARK.md) for methodology",
        "before quoting any number below.",
        "",
        f"- **Generated:** {generated_at}",
        f"- **Host context:** {os.cpu_count()} logical CPUs, {platform.system()} {platform.machine()}",
        f"- **Seeded rows:** {report.seeded_rows} · **Iterations/scenario:** "
        f"{report.iterations_per_scenario} (+{report.warmup_per_scenario} warmup) "
        f"· **Dialect:** {report.dialect}",
        "",
        "| Scenario | Tier | Mean ms | p50 ms | p95 ms | p99 ms |",
        "|---|---|---|---|---|---|",
    ]
    for scenario in report.scenarios:
        for tier_name, stats in (
            ("baseline", scenario.baseline),
            ("pipeline", scenario.pipeline),
            ("rest", scenario.rest),
        ):
            lines.append(
                f"| {scenario.name} | {tier_name} | {stats.mean_ms:.2f} | {stats.p50_ms:.2f} "
                f"| {stats.p95_ms:.2f} | {stats.p99_ms:.2f} |"
            )
        lines.append(
            f"| {scenario.name} | *overhead* | pipeline +{scenario.pipeline_overhead_ms:.2f}ms, "
            f"rest +{scenario.rest_overhead_ms:.2f}ms ({scenario.rest_overhead_pct:.0f}% of baseline) "
            "| | | |"
        )
    lines.append("")
    lines.append(
        f"**Mean pipeline overhead (no HTTP):** {report.mean_pipeline_overhead_ms:.2f} ms/query  \n"
        f"**Mean REST overhead (full round trip):** {report.mean_rest_overhead_ms:.2f} ms/query"
    )
    lines.append("")
    lines.append(
        "All figures are wall-clock milliseconds, in-process (ASGI transport, no real "
        "socket/TLS). Regenerate with `make performance-benchmark`."
    )
    return "\n".join(lines) + "\n"


def _cmd_run(args: argparse.Namespace) -> int:
    report = asyncio.run(
        run_performance_benchmark(
            connection_string=args.connection_string,
            rows=args.rows,
            iterations=args.iterations,
            warmup=args.warmup,
        )
    )

    if args.json:
        print(report.model_dump_json(indent=2))
    else:
        _print_report(report)

    if args.markdown_out is not None:
        args.markdown_out.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_out.write_text(_render_markdown(report))
        print(f"\nWrote {args.markdown_out}")

    if args.max_overhead_ms is not None:
        over = [s for s in report.scenarios if s.rest_overhead_ms > args.max_overhead_ms]
        if over:
            names = ", ".join(f"{s.name} (+{s.rest_overhead_ms:.2f}ms)" for s in over)
            print(f"\nRESULT: FAILED — over --max-overhead-ms={args.max_overhead_ms}: {names}")
            return 1
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="querygate-performance-benchmark",
        description="Measure QueryGate's per-request latency overhead against a real database.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    run_p = sub.add_parser("run", help="Run the benchmark and print a report.")
    run_p.add_argument(
        "--connection-string",
        default=DEFAULT_CONNECTION_STRING,
        # Never interpolate DEFAULT_CONNECTION_STRING into help text: if an
        # operator has exported QUERYGATE_DEMO_URL with a real credential to
        # point this at a non-demo database, `--help` would print it to
        # stdout / a CI log (2026-08-11 security-invariant-reviewer finding).
        help=(
            "Postgres connection string (default: the local demo DB from "
            "`make compose-up`, or $QUERYGATE_DEMO_URL if set)."
        ),
    )
    run_p.add_argument(
        "--rows", type=int, default=5000, help="Rows to seed in the benchmark table."
    )
    run_p.add_argument(
        "--iterations", type=int, default=30, help="Measured iterations per scenario."
    )
    run_p.add_argument(
        "--warmup", type=int, default=5, help="Warmup iterations per scenario (discarded)."
    )
    run_p.add_argument("--json", action="store_true", help="Emit the machine-readable report.")
    run_p.add_argument(
        "--max-overhead-ms",
        type=float,
        default=None,
        help="Optional sanity gate: exit 1 if any scenario's mean REST overhead exceeds this.",
    )
    run_p.add_argument(
        "--markdown-out",
        type=Path,
        default=DEFAULT_MARKDOWN_PATH,
        help=(
            "Write a fresh, publish-ready Markdown results snapshot here on every run "
            f"(default: {DEFAULT_MARKDOWN_PATH.relative_to(_REPO_ROOT)}, overwritten each "
            "time). Pass --no-markdown to skip."
        ),
    )
    run_p.add_argument(
        "--no-markdown",
        dest="markdown_out",
        action="store_const",
        const=None,
        help="Skip writing the Markdown results snapshot.",
    )
    run_p.set_defaults(func=_cmd_run)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
